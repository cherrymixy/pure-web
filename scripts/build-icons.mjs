// Regenerates components/ui/icons/registry.ts from components/ui/icons/svg/*.svg (exported from Figma, STEP 21).
// Run: node scripts/build-icons.mjs
import fs from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "components/ui/icons/svg");
const entries = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".svg"))
  .sort()
  .map((f) => {
    const svg = fs.readFileSync(path.join(dir, f), "utf8");
    const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
    const width = Number(svg.match(/<svg[^>]*\swidth="([\d.]+)"/)[1]);
    const height = Number(svg.match(/<svg[^>]*\sheight="([\d.]+)"/)[1]);
    const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
    return [f.replace(/\.svg$/, ""), { viewBox, width, height, body }];
  });

const out = `// Generated by scripts/build-icons.mjs from components/ui/icons/svg — do not edit by hand.
// Source: Figma xp0RmyE9WwsNFAF5kE88OX — F / Icon (458:9643, Material Symbols Round 24px) and web prototype icons (407:44879).
export const ICONS = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;

export type IconName = keyof typeof ICONS;
`;
fs.writeFileSync(path.join(process.cwd(), "components/ui/icons/registry.ts"), out);
console.log(`${entries.length} icons`);
